SELECT  C.NOMBRE,
e.NOMBRE || ' ' || e.APELLIDO_PATERNO "ENTRENADOR",
c.CUPOS "CUPOS",
NVL(COUNT (i.ID_SOCIO),0) "INSCRIPCIONES",
ROUND(NVL(COUNT(i.ID_SOCIO), 0) / NULLIF (c.CUPOS, 0)
* 100, 2) AS "%_OCUPACION"
FROM CLASE_GYM c
INNER JOIN ENTRENADOR e
ON c.ID_ENTRENADOR = e.ID_ENTRENADOR
LEFT JOIN CLASE_INSCRIPCION i
ON i.ID_CLASE = c.ID_CLASE
GROUP BY c.nombre, e.NOMBRE, e.APELLIDO_PATERNO, c.CUPOS
ORDER BY c.NOMBRE;

