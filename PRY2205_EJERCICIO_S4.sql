SELECT
s.NOMBRE || ' ' || s.APELLIDO_PATERNO || ' ' || s.APELLIDO_MATERNO AS 
"NOMBRE SOCIO",
c.NOMBRE AS "NOMBRE_CLASE",
e.NOMBRE || ' ' || e.APELLIDO_PATERNO AS "NOMBRE ENTRENADOR",
    CASE 
        WHEN i.ID_SOCIO is not null then 'INSCRITO'
        ELSE 'SIN INSCRIPCION'
    END AS "ESTADO_INSCRIPCION"
FROM SOCIO_GYM s
INNER JOIN CLASE_INSCRIPCION i ON s.ID_SOCIO = i.ID_SOCIO
RIGHT JOIN CLASE_GYM c ON i.ID_CLASE = c.ID_CLASE
LEFT JOIN ENTRENADOR e ON c.ID_ENTRENADOR = e.ID_ENTRENADOR














