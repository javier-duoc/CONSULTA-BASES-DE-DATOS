SELECT c.NOMBRE,
TO_CHAR (c.FECHA_HORA, 'DD/MM/YYYY HH24:MI') AS "FECHA_HORA",
e.NOMBRE|| ' ' || e.APELLIDO_PATERNO|| ' ' || e.APELLIDO_MATERNO AS "NOMBRE ENTRENADOR",
s.NOMBRE || ' ' || s.APELLIDO_PATERNO || ' ' || s.APELLIDO_MATERNO AS "NOMBRE SOCIO"
FROM CLASE_GYM c
INNER JOIN ENTRENADOR e 
ON c.ID_ENTRENADOR = e.ID_ENTRENADOR
INNER JOIN CLASE_INSCRIPCION i
ON i.ID_CLASE = c.ID_CLASE
INNER JOIN SOCIO_GYM s
ON s.ID_SOCIO = i.ID_SOCIO
ORDER BY c.FECHA_HORA;
